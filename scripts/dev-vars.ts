/**
 * Creates/updates apps/web/.dev.vars (gitignored): LOCAL Worker vars/secrets for `vite dev` / `vite preview`.
 * These override the fail-closed production defaults in apps/web/wrangler.jsonc, for local use only.
 *   BETTER_AUTH_SECRET   random per developer (48 bytes, base64url); preserved if already present
 *   APP_ENV=development  enables origin inference and the localhost-only dev mailbox
 *   EMAIL_TRANSPORT=dev-mailbox, AUTH_SIGNUP_ENABLED=true  (local only; Resend is not needed)
 * Never put production secrets here. Production secrets: `wrangler secret put BETTER_AUTH_SECRET` etc.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './usd.ts';

const file = join(ROOT, 'apps', 'web', '.dev.vars');
const current = new Map<string, string>();
if (existsSync(file)) {
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (m) current.set(m[1]!, m[2]!);
  }
}
const defaults: [string, string][] = [
  ['BETTER_AUTH_SECRET', randomBytes(48).toString('base64url')],
  ['APP_ENV', 'development'],
  ['EMAIL_TRANSPORT', 'dev-mailbox'],
  ['EMAIL_FROM', 'AR Creator <dev@localhost.invalid>'],
  ['AUTH_SIGNUP_ENABLED', 'true'],
];
let added = 0;
for (const [k, v] of defaults) {
  if (!current.has(k)) {
    current.set(k, v);
    added++;
  }
}
const header = '# LOCAL development only — gitignored. Generated by scripts/dev-vars.ts. Never put production secrets here.';
writeFileSync(file, [header, ...[...current].map(([k, v]) => `${k}=${v}`), ''].join('\n'), { mode: 0o600 });
console.log(added ? `apps/web/.dev.vars: added ${added} local setting(s)` : 'apps/web/.dev.vars: already configured');
