/**
 * Creates/updates the gitignored repo-root `.env` with LOCAL development database settings:
 *   POSTGRES_PASSWORD   random per developer (Docker container)
 *   AR_DB_PORT          loopback port (default 54320)
 *   DATABASE_URL        used by drizzle-kit and DB tests (local only)
 *   CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_HYPERDRIVE
 *                       used by the Worker in `vite dev`/`vite preview` instead of the real Hyperdrive
 * Existing values are preserved. Never put production (Neon) credentials in this file.
 *   node --experimental-strip-types scripts/db-env.ts
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './usd.ts';

const file = join(ROOT, '.env');
const current = new Map<string, string>();
if (existsSync(file)) {
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (m) current.set(m[1]!, m[2]!);
  }
}

const password = current.get('POSTGRES_PASSWORD') ?? randomBytes(24).toString('base64url');
const port = current.get('AR_DB_PORT') ?? '54320';
const url = `postgres://ar_creator:${password}@127.0.0.1:${port}/ar_creator`;
const wanted: [string, string][] = [
  ['POSTGRES_PASSWORD', password],
  ['AR_DB_PORT', port],
  ['DATABASE_URL', current.get('DATABASE_URL') ?? url],
  ['CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_HYPERDRIVE', current.get('CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_HYPERDRIVE') ?? url],
];

let added = 0;
for (const [k, v] of wanted) {
  if (!current.has(k)) {
    current.set(k, v);
    added++;
  }
}
const header = '# LOCAL development only — gitignored. Generated by scripts/db-env.ts. Never put production credentials here.';
writeFileSync(file, [header, ...[...current].map(([k, v]) => `${k}=${v}`), ''].join('\n'), { mode: 0o600 });
console.log(added ? `.env: added ${added} local database setting(s)` : '.env: local database settings already present');
